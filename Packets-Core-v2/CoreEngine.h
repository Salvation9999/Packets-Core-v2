#pragma once

//memo:
//1. 没有状态查询接口，调用方只能“相信” CoreStart / CoreStop 成功，无法询问当前是否已启动、是否正在停止
//2. 接口假设调用方是懂行的，没有防御式设计，这是给“自己/同类开发者”用的，不是库级 API

bool CoreStart(); // 启动核心逻辑
// 功能包含：
// - 启动命名管道发送线程（IPC）
// - 初始化网络 Hook（send / recv）
// - 启动 Hook 看门狗（对抗 ws2_32 prologue 还原）
//
// 线程安全假设：
// - 设计为在“工作线程 / 外部控制线程”中调用
// - 不应在 DllMain 或 Loader Lock 环境下调用


void CoreStop(); // 停止核心逻辑
// 功能包含：
// - 通知所有后台线程退出（软停止）
// - 停止 Hook 看门狗
// - 卸载网络 Hook
// - 停止 IPC 线程
//
// 语义说明：
// - 不保证所有数据被完整处理
// - 目标是安全卸载，而非严格一致性回收